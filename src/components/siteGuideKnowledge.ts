const ARABIC_STOP_WORDS = new Set([
  'في', 'من', 'على', 'عن', 'إلى', 'الى', 'مع', 'هذا', 'هذه', 'هو', 'هي',
  'ما', 'ماذا', 'هل', 'كيف', 'أين', 'اين', 'متى', 'كم', 'كل', 'أو', 'او',
  'لا', 'لم', 'لن', 'ان', 'أن', 'إن', 'الذي', 'التي', 'قد', 'كان', 'كانت'
]);

export function findLocalGuideMatch(query: string): SiteGuideResponse | null {
  if (!query) return null;
  const cleanQuery = query.toLowerCase().replace(/[^\w\s\u0621-\u064A]/g, ' ').trim();
  if (!cleanQuery) return null;

  const queryWords = cleanQuery
    .split(/\s+/)
    .filter(w => w.length >= 3 && !ARABIC_STOP_WORDS.has(w));

  let bestMatch: SiteGuideResponse | null = null;
  let highestScore = 0;

  for (const item of localKnowledgeBase) {
    let score = 0;

    for (const kw of item.keywords) {
      const cleanKw = kw.toLowerCase().trim();
      if (!cleanKw) continue;

      // Exact substring/phrase match gives high score
      if (cleanQuery.includes(cleanKw)) {
        score += cleanKw.includes(' ') ? 15 : 8;
      } else {
        // Word-level strict match (not partial substring)
        const kwWords = cleanKw.split(/\s+/).filter(w => w.length >= 3 && !ARABIC_STOP_WORDS.has(w));
        for (const qw of queryWords) {
          if (kwWords.includes(qw)) {
            score += 4;
          }
        }
      }
    }

    if (score > highestScore) {
      highestScore = score;
      bestMatch = item.response;
    }
  }

  // Only return if confidence threshold is met
  return highestScore >= 6 ? bestMatch : null;
}
