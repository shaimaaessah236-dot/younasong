/**
 * دالة البحث المتقدم ومطابقة الأغنية لجلب كلماتها الموثقة
 */
export function findSongLyrics(title: string, anime?: string | null): SpacetoonLyricItem | null {
  if (!title && !anime) return null;

  const normTitle = normalizeArabic(title);
  const normAnime = normalizeArabic(anime || '');

  // 1. مطابقة مباشرة لعنوان الشارة أو الأنمي
  for (const item of SPACETOON_LYRICS_COLLECTION) {
    const normItemTitle = normalizeArabic(item.songTitle);
    const normItemAnime = normalizeArabic(item.animeTitle);

    if (
      (normTitle && normItemTitle && (normTitle.includes(normItemTitle) || normItemTitle.includes(normTitle))) ||
      (normAnime && normItemAnime && (normAnime.includes(normItemAnime) || normItemAnime.includes(normAnime)))
    ) {
      return item;
    }
  }

  // 2. مطابقة بالوسوم
  for (const item of SPACETOON_LYRICS_COLLECTION) {
    for (const tag of item.tags || []) {
      const normTag = normalizeArabic(tag);
      if (normTag.length > 2 && (normTitle.includes(normTag) || normAnime.includes(normTag))) {
        return item;
      }
    }
  }

  // 3. مطابقة الكلمات المفتاحية الفريدة
  for (const item of SPACETOON_LYRICS_COLLECTION) {
    const keyWords = item.summary.split(' ').map(w => normalizeArabic(w)).filter(w => w.length > 3);
    for (const kw of keyWords.slice(0, 5)) {
      if (normTitle.includes(kw) || normAnime.includes(kw)) {
        return item;
      }
    }
  }

  return null;
}

/**
 * دالة التحقق مما إذا كان التسجيل يطابق استعلام البحث:
 * تشمل العنوان، اسم الأنمي، اسم الفنان، ملخص الكلمات، والكلمات الأصلية الكاملة!
 */
export function matchesSearchQueryWithLyrics(rec: Recording, query: string): boolean {
  if (!query || !query.trim()) return true;

  const qNorm = normalizeArabic(query);
  if (!qNorm) return true;

  // 1. مطابقة مباشرة سريعة للنص الكامل
  if (
    normalizeArabic(rec.title).includes(qNorm) ||
    (rec.song?.title && normalizeArabic(rec.song.title).includes(qNorm)) ||
    (rec.song?.originalTitle && normalizeArabic(rec.song.originalTitle).includes(qNorm)) ||
    (rec.artist && normalizeArabic(rec.artist).includes(qNorm)) ||
    (rec.artists?.some(a => normalizeArabic(a.name).includes(qNorm))) ||
    (rec.animeList?.some(an => normalizeArabic(an.title).includes(qNorm))) ||
    (rec.lyricsSummary && normalizeArabic(rec.lyricsSummary).includes(qNorm)) ||
    (rec.fullLyrics && normalizeArabic(rec.fullLyrics).includes(qNorm)) ||
    (rec.lyrics && normalizeArabic(rec.lyrics).includes(qNorm)) ||
    (rec.song?.lyrics && normalizeArabic(rec.song.lyrics).includes(qNorm))
  ) {
    return true;
  }

  // 2. مطابقة الكتالوج الموثق المباشر
  const matched = findSongLyrics(rec.title, rec.animeList?.[0]?.title || rec.song?.originalTitle);
  if (matched) {
    if (normalizeArabic(matched.lyrics).includes(qNorm)) return true;
    if (normalizeArabic(matched.summary).includes(qNorm)) return true;
    if (normalizeArabic(matched.songTitle).includes(qNorm)) return true;
    if (normalizeArabic(matched.animeTitle).includes(qNorm)) return true;
  }

  // 3. مطابقة الكلمات والرموز المتعددة (Multi-token Word-by-Word Matching)
  // تتيح البحث المركب مثل: "شارة القناص رشا" أو "ريمي دراغون بول" أو "كونان طارق العربي"
  const tokens = qNorm.split(/\s+/).filter(t => t.length > 1);
  if (tokens.length > 1) {
    const combined = [
      rec.title,
      rec.song?.title,
      rec.song?.originalTitle,
      rec.artist,
      rec.artists?.map(a => a.name).join(' '),
      rec.animeList?.map(an => an.title).join(' '),
      rec.lyrics,
      rec.fullLyrics,
      rec.lyricsSummary,
      rec.song?.lyrics,
      matched?.lyrics,
      matched?.songTitle,
      matched?.animeTitle,
      rec.categories?.map(c => c.name).join(' '),
      rec.tags?.join(' ')
    ].filter(Boolean).map(s => normalizeArabic(s)).join(' ');

    // تصفية الكلمات الزائدة العامة إذا كان الاستعلام طويلاً (مثل شارة، أغنية، كرتون)
    const significantTokens = tokens.filter(tok => !['شاره', 'اغنيه', 'كرتون', 'انمي', 'سبيستون', 'song', 'theme'].includes(tok));
    const targetTokens = significantTokens.length > 0 ? significantTokens : tokens;

    const allTokensFound = targetTokens.every(tok => combined.includes(tok));
    if (allTokensFound) return true;
  }

  return false;
}
