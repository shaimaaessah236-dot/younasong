/**
 * دالة تطبيع النص العربي للبحث الفوري الذكي
 * تضمن مطابقة الكلمات والعبارات بدقة وسرعة بغض النظر عن:
 * الهمزات (أ, إ, آ, ا), التاء المربوطة والهاء (ة, ه), الياء والألف المقصورة (ي, ى), التشكيل, والتطويل (ـ)
 */
export function normalizeArabic(text: string | null | undefined): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '') // إزالة علامات التشكيل والتنوين
    .replace(/ـ+/g, '') // إزالة التطويل
    .replace(/[أإآٱ]/g, 'ا') // توحيد الهمزات إلى ألف
    .replace(/ة/g, 'ه') // توحيد التاء المربوطة
    .replace(/[ىي]/g, 'ي') // توحيد الياء والألف المقصورة
    .replace(/[^\w\s\u0600-\u06FF]/gi, ' ') // استبدال الرموز بمسافات
    .replace(/\s+/g, ' ')
    .trim();
}

